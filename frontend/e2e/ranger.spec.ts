import { test, expect } from '@playwright/test'

test('landing, real synthetic demo, navigation and tag correction',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading',{name:/your money.*in the.*wild/i})).toBeVisible()
  await page.getByRole('link',{name:'Explore the demo'}).click()
  await expect(page.getByRole('heading',{name:/howdy, trailblazer/i})).toBeVisible()
  await expect(page.getByText('Fictional receipts · processed by the real parser')).toBeVisible()
  await expect(page.locator('.total-amount')).toContainText('₹2,036')
  await expect(page.getByText('₹979',{exact:true})).toBeVisible()
  await page.locator('.side-nav:visible a[href="/app/trail"], .mobile-nav:visible a[href="/app/trail"]').click()
  await expect(page.getByRole('heading',{name:/follow the money/i})).toBeVisible()
  await page.getByLabel('Search receipts').fill('Midnight Burger')
  await expect(page.locator('.ledger-row')).toHaveCount(1)
  await page.getByLabel('Search receipts').fill('')
  await page.getByRole('button',{name:'Late night',exact:true}).click()
  await expect(page.locator('.ledger-row')).toHaveCount(3)
  await page.getByRole('button',{name:'All receipts',exact:true}).click()
  await page.getByRole('button',{name:/Midnight Burger Co/i}).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button',{name:'✳ Junk food'}).first().click()
  await expect(page.getByRole('button',{name:'+ Mark junk'}).first()).toBeVisible()
  await page.getByRole('button',{name:'Close'}).click()
  await page.locator('.side-nav:visible a[href="/app/camp"], .mobile-nav:visible a[href="/app/camp"]').click()
  await expect(page.getByText('₹739',{exact:true})).toBeVisible()
  expect(errors).toEqual([])
})
