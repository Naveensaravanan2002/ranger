test('responsive pages do not overflow horizontally and settings save',async({page})=>{
  for(const path of ['/','/app/camp','/app/trail','/app/stash','/privacy']){
    await page.goto(path)
    await page.waitForTimeout(500)
    const width=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}))
    expect(width.scroll).toBeLessThanOrEqual(width.client+1)
  }
  await page.goto('/app/camp')
  await page.locator('.top-icon:visible, .mobile-nav:visible button').first().click()
  await page.getByLabel('Starts').fill('22:00')
  await page.getByRole('button',{name:'Save preferences'}).click()
  await expect(page.getByText('Display settings saved in this browser.')).toBeVisible()
})

